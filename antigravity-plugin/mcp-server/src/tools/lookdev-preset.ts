import type { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js'
import { z } from 'zod'
import { jsonPayload, leasedText, text, type GatewayClient } from '../gateway-client.js'
import {
  bufferToImageContent,
  errorResult,
  textResult,
  type McpContentItem,
  type McpToolResult,
} from '../media.js'

const PRESETS = [
  'car_paint_clearcoat',
  'automotive_glass',
  'brushed_alloy',
  'carbon_fiber',
  'tire_rubber',
  'studio_three_point_agx',
] as const

type PresetName = (typeof PRESETS)[number]

function buildLookdevPython(
  preset: PresetName,
  targets: string[],
  materialName: string,
  overrides: Record<string, unknown>,
): string {
  return [
    'import bpy, math, json',
    `PRESET = ${JSON.stringify(preset)}`,
    `TARGETS = ${JSON.stringify(targets)}`,
    `MAT_NAME = ${JSON.stringify(materialName)}`,
    `OVR = json.loads(${JSON.stringify(JSON.stringify(overrides))})`,
    '',
    'def _set_input(node, names, val):',
    '    if isinstance(names, str):',
    '        names = [names]',
    '    for n in names:',
    '        if n in node.inputs:',
    '            node.inputs[n].default_value = val',
    '            return n',
    '    return None',
    '',
    'def _resolve_targets():',
    '    objs = []',
    '    if TARGETS:',
    '        for name in TARGETS:',
    '            o = bpy.data.objects.get(name)',
    '            if o is not None and o.type in ("MESH", "CURVE", "SURFACE"):',
    '                objs.append(o)',
    '    else:',
    '        objs = [o for o in bpy.context.selected_objects if o.type in ("MESH", "CURVE", "SURFACE")]',
    '        if not objs and bpy.context.active_object and bpy.context.active_object.type in ("MESH", "CURVE", "SURFACE"):',
    '            objs = [bpy.context.active_object]',
    '    return objs',
    '',
    'def _assign_mat(mat, objs):',
    '    assigned = []',
    '    for o in objs:',
    '        if o.data.materials:',
    '            o.data.materials[0] = mat',
    '        else:',
    '            o.data.materials.append(mat)',
    '        assigned.append(o.name)',
    '    return assigned',
    '',
    'def _fresh_mat(name):',
    '    mat = bpy.data.materials.get(name) or bpy.data.materials.new(name=name)',
    '    mat.use_nodes = True',
    '    nt = mat.node_tree',
    '    nt.nodes.clear()',
    '    out = nt.nodes.new("ShaderNodeOutputMaterial")',
    '    out.location = (500, 0)',
    '    bsdf = nt.nodes.new("ShaderNodeBsdfPrincipled")',
    '    bsdf.location = (180, 0)',
    '    nt.links.new(bsdf.outputs["BSDF"], out.inputs["Surface"])',
    '    return mat, nt, bsdf, out',
    '',
    'COLOR_SWATCHES = {',
    '    "rosso_corsa": (0.62, 0.015, 0.015, 1.0),',
    '    "midnight_blue": (0.012, 0.035, 0.14, 1.0),',
    '    "liquid_silver": (0.58, 0.60, 0.63, 1.0),',
    '    "emerald_green": (0.012, 0.16, 0.08, 1.0),',
    '    "pearl_white": (0.85, 0.85, 0.84, 1.0),',
    '    "stealth_grey": (0.14, 0.15, 0.16, 1.0),',
    '}',
    '',
    'def _resolve_rgba(default_rgba):',
    '    c = OVR.get("base_color")',
    '    if isinstance(c, str) and c.lower() in COLOR_SWATCHES:',
    '        return COLOR_SWATCHES[c.lower()]',
    '    if isinstance(c, (list, tuple)) and len(c) >= 3:',
    '        return (float(c[0]), float(c[1]), float(c[2]), float(c[3]) if len(c) > 3 else 1.0)',
    '    return default_rgba',
    '',
    'def _build_car_paint():',
    '    name = MAT_NAME or "AGY_CarPaint_Clearcoat"',
    '    mat, nt, bsdf, _ = _fresh_mat(name)',
    '    base_rgba = _resolve_rgba(COLOR_SWATCHES["rosso_corsa"])',
    '    # Metallic micro-flake variation via Voronoi + Layer Weight Fresnel shift',
    '    tex_coord = nt.nodes.new("ShaderNodeTexCoord")',
    '    tex_coord.location = (-720, 120)',
    '    vor = nt.nodes.new("ShaderNodeTexVoronoi")',
    '    vor.location = (-480, -60)',
    '    vor.inputs["Scale"].default_value = float(OVR.get("flake_scale", 220.0))',
    '    nt.links.new(tex_coord.outputs["Object"], vor.inputs["Vector"])',
    '    bump = nt.nodes.new("ShaderNodeBump")',
    '    bump.location = (-220, -140)',
    '    bump.inputs["Strength"].default_value = float(OVR.get("flake_strength", 0.025))',
    '    bump.inputs["Distance"].default_value = 0.002',
    '    nt.links.new(vor.outputs["Distance"], bump.inputs["Height"])',
    '    nt.links.new(bump.outputs["Normal"], bsdf.inputs["Normal"])',
    '    lw = nt.nodes.new("ShaderNodeLayerWeight")',
    '    lw.location = (-480, 220)',
    '    lw.inputs["Blend"].default_value = 0.35',
    '    mix = nt.nodes.new("ShaderNodeMix")',
    '    mix.data_type = "RGBA"',
    '    mix.location = (-180, 180)',
    '    darker = (base_rgba[0] * 0.45, base_rgba[1] * 0.45, base_rgba[2] * 0.45, 1.0)',
    '    mix.inputs["A"].default_value = base_rgba',
    '    mix.inputs["B"].default_value = darker',
    '    nt.links.new(lw.outputs["Facing"], mix.inputs["Factor"])',
    '    nt.links.new(mix.outputs["Result"], bsdf.inputs["Base Color"])',
    '    _set_input(bsdf, "Metallic", float(OVR.get("metallic", 0.82)))',
    '    _set_input(bsdf, "Roughness", float(OVR.get("roughness", 0.22)))',
    '    _set_input(bsdf, ["Specular IOR Level", "Specular"], float(OVR.get("specular", 0.55)))',
    '    _set_input(bsdf, ["Coat Weight", "Clearcoat"], float(OVR.get("coat_weight", 1.0)))',
    '    _set_input(bsdf, ["Coat Roughness", "Clearcoat Roughness"], float(OVR.get("coat_roughness", 0.03)))',
    '    _set_input(bsdf, "Coat IOR", float(OVR.get("coat_ior", 1.52)))',
    '    return mat',
    '',
    'def _build_automotive_glass():',
    '    name = MAT_NAME or "AGY_Automotive_Glass"',
    '    mat, nt, bsdf, _ = _fresh_mat(name)',
    '    tint = _resolve_rgba((0.06, 0.08, 0.09, 1.0))',
    '    _set_input(bsdf, "Base Color", tint)',
    '    _set_input(bsdf, "Metallic", 0.0)',
    '    _set_input(bsdf, "Roughness", float(OVR.get("roughness", 0.02)))',
    '    _set_input(bsdf, "IOR", float(OVR.get("ior", 1.52)))',
    '    _set_input(bsdf, ["Transmission Weight", "Transmission"], float(OVR.get("transmission", 0.92)))',
    '    _set_input(bsdf, "Alpha", float(OVR.get("alpha", 0.35)))',
    '    _set_input(bsdf, ["Coat Weight", "Clearcoat"], 0.6)',
    '    _set_input(bsdf, ["Coat Roughness", "Clearcoat Roughness"], 0.01)',
    '    return mat',
    '',
    'def _build_brushed_alloy():',
    '    name = MAT_NAME or "AGY_Brushed_Alloy"',
    '    mat, nt, bsdf, _ = _fresh_mat(name)',
    '    tc = nt.nodes.new("ShaderNodeTexCoord")',
    '    tc.location = (-720, 0)',
    '    mp = nt.nodes.new("ShaderNodeMapping")',
    '    mp.location = (-520, 0)',
    '    mp.inputs["Scale"].default_value = (1.0, 28.0, 1.0)',
    '    noise = nt.nodes.new("ShaderNodeTexNoise")',
    '    noise.location = (-320, 0)',
    '    noise.inputs["Scale"].default_value = 35.0',
    '    noise.inputs["Detail"].default_value = 8.0',
    '    ramp = nt.nodes.new("ShaderNodeValToRGB")',
    '    ramp.location = (-100, -40)',
    '    ramp.color_ramp.elements[0].position = 0.2',
    '    ramp.color_ramp.elements[0].color = (0.14, 0.14, 0.14, 1.0)',
    '    ramp.color_ramp.elements[1].position = 0.85',
    '    ramp.color_ramp.elements[1].color = (0.28, 0.28, 0.28, 1.0)',
    '    nt.links.new(tc.outputs["Object"], mp.inputs["Vector"])',
    '    nt.links.new(mp.outputs["Vector"], noise.inputs["Vector"])',
    '    nt.links.new(noise.outputs["Fac"], ramp.inputs["Fac"])',
    '    nt.links.new(ramp.outputs["Color"], bsdf.inputs["Roughness"])',
    '    _set_input(bsdf, "Base Color", _resolve_rgba((0.76, 0.78, 0.80, 1.0)))',
    '    _set_input(bsdf, "Metallic", float(OVR.get("metallic", 0.98)))',
    '    _set_input(bsdf, "Anisotropic", float(OVR.get("anisotropic", 0.55)))',
    '    return mat',
    '',
    'def _build_carbon_fiber():',
    '    name = MAT_NAME or "AGY_Carbon_Fiber"',
    '    mat, nt, bsdf, _ = _fresh_mat(name)',
    '    tc = nt.nodes.new("ShaderNodeTexCoord")',
    '    tc.location = (-740, 0)',
    '    chk = nt.nodes.new("ShaderNodeTexChecker")',
    '    chk.location = (-480, 80)',
    '    chk.inputs["Scale"].default_value = float(OVR.get("weave_scale", 120.0))',
    '    chk.inputs["Color1"].default_value = (0.025, 0.025, 0.028, 1.0)',
    '    chk.inputs["Color2"].default_value = (0.065, 0.068, 0.072, 1.0)',
    '    bump = nt.nodes.new("ShaderNodeBump")',
    '    bump.location = (-200, -120)',
    '    bump.inputs["Strength"].default_value = 0.08',
    '    bump.inputs["Distance"].default_value = 0.002',
    '    nt.links.new(tc.outputs["Object"], chk.inputs["Vector"])',
    '    nt.links.new(chk.outputs["Color"], bsdf.inputs["Base Color"])',
    '    nt.links.new(chk.outputs["Fac"], bump.inputs["Height"])',
    '    nt.links.new(bump.outputs["Normal"], bsdf.inputs["Normal"])',
    '    _set_input(bsdf, "Metallic", 0.25)',
    '    _set_input(bsdf, "Roughness", 0.26)',
    '    _set_input(bsdf, ["Coat Weight", "Clearcoat"], float(OVR.get("coat_weight", 1.0)))',
    '    _set_input(bsdf, ["Coat Roughness", "Clearcoat Roughness"], float(OVR.get("coat_roughness", 0.04)))',
    '    return mat',
    '',
    'def _build_tire_rubber():',
    '    name = MAT_NAME or "AGY_Tire_Rubber"',
    '    mat, nt, bsdf, _ = _fresh_mat(name)',
    '    tc = nt.nodes.new("ShaderNodeTexCoord")',
    '    tc.location = (-680, -80)',
    '    noise = nt.nodes.new("ShaderNodeTexNoise")',
    '    noise.location = (-440, -80)',
    '    noise.inputs["Scale"].default_value = 260.0',
    '    noise.inputs["Detail"].default_value = 10.0',
    '    bump = nt.nodes.new("ShaderNodeBump")',
    '    bump.location = (-200, -120)',
    '    bump.inputs["Strength"].default_value = 0.06',
    '    bump.inputs["Distance"].default_value = 0.003',
    '    nt.links.new(tc.outputs["Object"], noise.inputs["Vector"])',
    '    nt.links.new(noise.outputs["Fac"], bump.inputs["Height"])',
    '    nt.links.new(bump.outputs["Normal"], bsdf.inputs["Normal"])',
    '    _set_input(bsdf, "Base Color", _resolve_rgba((0.022, 0.022, 0.024, 1.0)))',
    '    _set_input(bsdf, "Metallic", 0.0)',
    '    _set_input(bsdf, "Roughness", float(OVR.get("roughness", 0.68)))',
    '    _set_input(bsdf, ["Specular IOR Level", "Specular"], 0.28)',
    '    return mat',
    '',
    'def _ensure_collection(name):',
    '    col = bpy.data.collections.get(name)',
    '    if col is None:',
    '        col = bpy.data.collections.new(name)',
    '        bpy.context.scene.collection.children.link(col)',
    '    return col',
    '',
    'def _upsert_area_light(col, name, loc, rot_deg, energy, size_x, size_y, color):',
    '    obj = bpy.data.objects.get(name)',
    '    if obj is None:',
    '        ldata = bpy.data.lights.new(name=name, type="AREA")',
    '        obj = bpy.data.objects.new(name=name, object_data=ldata)',
    '        col.objects.link(obj)',
    '    else:',
    '        ldata = obj.data',
    '        ldata.type = "AREA"',
    '    ldata.shape = "RECTANGLE"',
    '    ldata.size = size_x',
    '    ldata.size_y = size_y',
    '    ldata.energy = energy',
    '    ldata.color = color',
    '    obj.location = loc',
    '    obj.rotation_euler = tuple(math.radians(a) for a in rot_deg)',
    '    return obj',
    '',
    'def _build_studio_agx():',
    '    scene = bpy.context.scene',
    '    # Color management: AgX',
    '    scene.view_settings.view_transform = "AgX"',
    '    look_name = str(OVR.get("agx_look", "AgX - Punchy"))',
    '    try:',
    '        scene.view_settings.look = look_name',
    '    except Exception:',
    '        scene.view_settings.look = "None"',
    '    scene.view_settings.exposure = float(OVR.get("exposure", 0.15))',
    '    engine = str(OVR.get("engine", "BLENDER_EEVEE_NEXT"))',
    '    try:',
    '        scene.render.engine = engine',
    '    except Exception:',
    '        pass',
    '    # World shader with optional HDRI + rotation',
    '    world = scene.world or bpy.data.worlds.new("AGY_Studio_World")',
    '    scene.world = world',
    '    world.use_nodes = True',
    '    wnt = world.node_tree',
    '    wnt.nodes.clear()',
    '    w_out = wnt.nodes.new("ShaderNodeOutputWorld")',
    '    w_out.location = (420, 0)',
    '    bg = wnt.nodes.new("ShaderNodeBackground")',
    '    bg.location = (180, 0)',
    '    bg.inputs["Strength"].default_value = float(OVR.get("world_strength", 0.35))',
    '    hdri_path = OVR.get("hdri_path")',
    '    if hdri_path:',
    '        tc = wnt.nodes.new("ShaderNodeTexCoord")',
    '        mp = wnt.nodes.new("ShaderNodeMapping")',
    '        mp.inputs["Rotation"].default_value = (0.0, 0.0, math.radians(float(OVR.get("hdri_rotation_deg", 0.0))))',
    '        env = wnt.nodes.new("ShaderNodeTexEnvironment")',
    '        env.image = bpy.data.images.load(str(hdri_path), check_existing=True)',
    '        wnt.links.new(tc.outputs["Generated"], mp.inputs["Vector"])',
    '        wnt.links.new(mp.outputs["Vector"], env.inputs["Vector"])',
    '        wnt.links.new(env.outputs["Color"], bg.inputs["Color"])',
    '    else:',
    '        bg.inputs["Color"].default_value = (0.045, 0.05, 0.06, 1.0)',
    '    wnt.links.new(bg.outputs["Background"], w_out.inputs["Surface"])',
    '    # Studio collection: 3-point softboxes + floor + camera',
    '    col = _ensure_collection("AGY_Studio_Rig")',
    '    scale = float(OVR.get("rig_scale", 1.0))',
    '    _upsert_area_light(col, "AGY_Key_Softbox", (4.5 * scale, -4.2 * scale, 3.8 * scale), (54, 0, 42), 900 * scale * scale, 4.5 * scale, 2.2 * scale, (1.0, 0.98, 0.95))',
    '    _upsert_area_light(col, "AGY_Fill_Softbox", (-4.8 * scale, -3.0 * scale, 2.6 * scale), (65, 0, -52), 380 * scale * scale, 5.0 * scale, 2.4 * scale, (0.86, 0.93, 1.0))',
    '    _upsert_area_light(col, "AGY_Rim_Overhead", (0.0, 3.6 * scale, 4.2 * scale), (-48, 0, 0), 650 * scale * scale, 6.0 * scale, 1.4 * scale, (0.95, 0.97, 1.0))',
    '    # Matte dark studio floor',
    '    floor = bpy.data.objects.get("AGY_Studio_Floor")',
    '    if floor is None:',
    '        bpy.ops.mesh.primitive_plane_add(size=24.0 * scale, location=(0.0, 0.0, 0.0))',
    '        floor = bpy.context.active_object',
    '        floor.name = "AGY_Studio_Floor"',
    '        for c in list(floor.users_collection):',
    '            c.objects.unlink(floor)',
    '        col.objects.link(floor)',
    '    fmat, _, fbsdf, _ = _fresh_mat("AGY_Studio_Floor_Mat")',
    '    _set_input(fbsdf, "Base Color", (0.04, 0.042, 0.048, 1.0))',
    '    _set_input(fbsdf, "Roughness", 0.42)',
    '    _assign_mat(fmat, [floor])',
    '    # Studio hero camera (3/4 automotive angle)',
    '    cam = bpy.data.objects.get("AGY_Studio_Camera")',
    '    if cam is None:',
    '        cdata = bpy.data.cameras.new("AGY_Studio_Camera")',
    '        cam = bpy.data.objects.new("AGY_Studio_Camera", cdata)',
    '        col.objects.link(cam)',
    '    cam.data.lens = float(OVR.get("camera_lens", 65.0))',
    '    cam.location = (3.8 * scale, -4.6 * scale, 1.65 * scale)',
    '    direction = bpy.data.objects.new("_tmp_dir", None)',
    '    bpy.data.objects.remove(direction)',
    '    from mathutils import Vector',
    '    target_pt = Vector(OVR.get("look_at", [0.0, 0.0, 0.75 * scale]))',
    '    cam.rotation_euler = (target_pt - cam.location).to_track_quat("-Z", "Y").to_euler()',
    '    scene.camera = cam',
    '    return {',
    '        "ok": True,',
    '        "preset": PRESET,',
    '        "view_transform": scene.view_settings.view_transform,',
    '        "look": scene.view_settings.look,',
    '        "engine": scene.render.engine,',
    '        "camera": cam.name,',
    '        "lights": ["AGY_Key_Softbox", "AGY_Fill_Softbox", "AGY_Rim_Overhead"],',
    '        "floor": floor.name,',
    '    }',
    '',
    'if PRESET == "studio_three_point_agx":',
    '    out = _build_studio_agx()',
    'else:',
    '    builders = {',
    '        "car_paint_clearcoat": _build_car_paint,',
    '        "automotive_glass": _build_automotive_glass,',
    '        "brushed_alloy": _build_brushed_alloy,',
    '        "carbon_fiber": _build_carbon_fiber,',
    '        "tire_rubber": _build_tire_rubber,',
    '    }',
    '    mat = builders[PRESET]()',
    '    objs = _resolve_targets()',
    '    assigned = _assign_mat(mat, objs)',
    '    out = {"ok": True, "preset": PRESET, "material": mat.name, "assigned_objects": assigned}',
    '',
    'print(json.dumps(out, ensure_ascii=False))',
  ].join('\n')
}

export function registerLookdevPresetTool(server: McpServer, client: GatewayClient): void {
  server.tool(
    'blender_lookdev_preset',
    '【跑车 LookDev 与棚拍预设】一键在 Blender 4.5 LTS 中生成并应用跑车级 PBR 材质（双层清漆车漆 car_paint_clearcoat、汽车玻璃 automotive_glass、拉丝合金 brushed_alloy、碳纤维 carbon_fiber、轮胎橡胶 tire_rubber）或 AgX 三点柔光棚拍布光（studio_three_point_agx）。',
    {
      preset: z
        .enum(PRESETS)
        .describe('预设名称：car_paint_clearcoat | automotive_glass | brushed_alloy | carbon_fiber | tire_rubber | studio_three_point_agx'),
      targets: z
        .array(z.string())
        .optional()
        .describe('要赋予材质的目标物体名称列表（材质预设有效；省略时自动作用于当前选中/活动物体）'),
      material_name: z.string().optional().describe('自定义材质名称（可选）'),
      overrides: z
        .unknown()
        .optional()
        .describe('可选参数覆盖 JSON，如 {"base_color":"rosso_corsa","coat_roughness":0.025} 或 {"agx_look":"AgX - Punchy","hdri_rotation_deg":45,"rig_scale":1.0}'),
      see: z.boolean().optional().describe('应用后是否顺带抓视口一帧转为 ImageContent 返回（默认 false）'),
    },
    async (args): Promise<McpToolResult> => {
      if (!(await client.ensureReady())) {
        return errorResult('gateway_unreachable', `Gateway 不可用（127.0.0.1:${client.port}）`)
      }
      const ready = await client.requireReadySession()
      if (!ready.ok) return textResult(ready.message, true)

      const code = buildLookdevPython(
        args.preset,
        args.targets ?? [],
        args.material_name ?? '',
        jsonPayload(args.overrides),
      )
      const r = await client.postJson(
        '/act',
        { code, file: null, py: true, sessionId: ready.sessionId, waitMs: 2000 },
        120000,
      )
      const lt = leasedText(r)
      if (lt) return textResult(lt, true)
      if (r.ok !== true) {
        return errorResult('lookdev_error', `LookDev 预设 ${args.preset} 失败 · ${text(r.error || r.raw || 'unknown')}`)
      }

      const content: McpContentItem[] = [{ type: 'text', text: text(r.stdout).trim() || `LOOKDEV ${args.preset} ok` }]
      if (args.see === true) {
        try {
          const frame = await client.fetchFrame(1024)
          content.push(bufferToImageContent(frame.png, 'image/png'))
        } catch (err) {
          content[0] = {
            type: 'text',
            text: `${content[0].type === 'text' ? content[0].text : ''}\n⚠ 抓帧失败：${err instanceof Error ? err.message : String(err)}`,
          }
        }
      }
      return { content }
    },
  )
}
